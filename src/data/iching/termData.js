    hexagramIds: o.hexagramIds || [],
    yaoIds: o.yaoIds || [],
    tenWingNodeIds: o.tenWingNodeIds || [],
    traditionIds: o.traditionIds || [],
    relatedTermIds: o.relatedTermIds || [],
    contrastTermIds: o.contrastTermIds || [],
