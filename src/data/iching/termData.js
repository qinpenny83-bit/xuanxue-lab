export const ALL_TERMS = [
  ...CORE, ...EXTRA_CORE,
  ...STRUCTURE, ...EXTRA_STRUCTURE,
  ...POSITION, ...EXTRA_POSITION,
  ...RELATION, ...EXTRA_RELATION,
  ...CLASSIC, ...EXTRA_CLASSIC,
  ...THOUGHT, ...EXTRA_THOUGHT,
  ...METHOD, ...EXTRA_METHOD,
  ...TRADITION, ...EXTRA_TRADITION,
]

export const TERM_BY_ID = ALL_TERMS.reduce((acc, t) => {
  acc[t.id] = t
  return acc
}, {})

// 去掉拼音声调与空格，便于「zhongzheng」式检索
function norm(s) {
  return (s || '').toString().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/\s+/g, '')
}

export const TERM_BY_TERM = ALL_TERMS.reduce((acc, t) => {
  acc[t.term] = t
  return acc
}, {})

const TERM_SEARCH_INDEX = ALL_TERMS.flatMap((t) => {
  const keys = new Set([t.term, t.traditionalTerm, norm(t.pinyin), ...(t.aliases || [])])
  return [...keys].map((k) => [k, t.id])
})

export function getTerm(idOrTerm) {
  return TERM_BY_ID[idOrTerm] || TERM_BY_TERM[idOrTerm] || null
}

export function termsByCategory(categoryId) {
  return ALL_TERMS.filter((t) => t.category === categoryId)
}

// 支持：中文 / 繁体 / 拼音（去声调）/ 别名 / 子串；空串返回全部（按层排序）
export function searchTerms(query) {
  const q = norm(query)
  if (!q) return ALL_TERMS
  const ids = []
  for (const [k, id] of TERM_SEARCH_INDEX) {
    if (norm(k).includes(q)) ids.push(id)
  }
  const seen = new Set()
  return ALL_TERMS.filter((t) => {
    if (norm(t.term).includes(q) || norm(t.traditionalTerm).includes(q) || t.aliases.some((a) => norm(a).includes(q)) || norm(t.pinyin).includes(q)) {
      if (!seen.has(t.id)) { seen.add(t.id); return true }
    }
    return false
  })
}

