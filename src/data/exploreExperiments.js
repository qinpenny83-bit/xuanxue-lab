function X(exp) {
  __xseq += 1
  const masteryKeys = [...new Set((exp.masteryKeys || []).map((k) => MASTERY_KEY_ALIAS[k] || k))]
  return {
    level: 1, // 1 入门 / 2 进阶 / 3 高阶 / 4 综合
    difficulty: 1,
    material: { kind: 'hexagram' },
    focus: [],
    compare: null,
    reflection: '',
    expectedSkills: [],
    errorTypes: [],
    masteryKeys: [],
    relatedTerms: [],
    __xseq,
    ...exp,
    expectedSkills: normalizeSkills(exp.expectedSkills),
    masteryKeys,
  }
}

