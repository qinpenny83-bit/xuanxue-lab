// expectedSkills 能力键规范化：与推理实验工厂共享同一 8 维词汇表，
// 保证四板块能力标记完全一致（知识覆盖审计收敛）。
const SKILL_ALIAS = {
  text: 'evidence',
  compare: 'synthesis',
  revise: 'reasoning',
  tradition: 'synthesis',
  reflection: 'uncertainty',
}
function normalizeSkills(list) {
  return [...new Set((list || []).map((k) => SKILL_ALIAS[k] || k))]
}

// 探索实验工厂：默认值补齐，条目只写差异字段
