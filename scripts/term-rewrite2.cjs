const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js') && !skip.has(f))
let totalFiles = 0
let totalHits = 0
for (const f of files) {
  const p = path.join(dir, f)
  let s = fs.readFileSync(p, 'utf8')
  const before = s
  let fileHits = 0
  for (const [a, b] of rules) {
    if (s.includes(a)) {
      const c = s.split(a).length - 1
      fileHits += c
      s = s.split(a).join(b)
    }
  }
  if (s !== before) {
    fs.writeFileSync(p, s, 'utf8')
    totalFiles++
    totalHits += fileHits
    console.log(`rewritten: ${f} (${fileHits}处)`)
  }
}
console.log(`\nfiles rewritten: ${totalFiles}, total hits: ${totalHits}`)
